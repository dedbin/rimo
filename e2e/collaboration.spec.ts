import { test, expect } from "./fixtures";
import { canvas, invitation, saved } from "./board-ui";

test("owner creates a board, guests collaborate, local undo preserves the peer and access is revoked", async ({ page, scenario }) => {
  await page.goto("/", { waitUntil: "domcontentloaded" });
  const created = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/boards" && response.request().method() === "POST");
  await page.getByRole("button", { name: "Создать доску", exact: true }).first().click();
  const response = await created;
  expect(response.status()).toBe(201);
  const { board } = await response.json() as { board: { id: string } };
  scenario.createdBoards.add(board.id);
  await expect(page).toHaveURL(new RegExp(`/board/${board.id}$`));
  await expect(canvas(page)).toBeVisible();
  await saved(page);
  const editor = await scenario.guest(await invitation(page, "editor"), "E2E ученик");
  await page.getByRole("button", { name: /^Прямоугольник/ }).click();
  await page.mouse.click(430, 320);
  const rectangle = canvas(page).locator("[data-layer-id] > rect");
  await expect(rectangle).toHaveCount(1);
  await expect(canvas(editor).locator("[data-layer-id] > rect")).toHaveCount(1);
  await saved(page);
  const initial = await rectangle.boundingBox();
  if (!initial) throw new Error("Rectangle is not visible");
  await editor.getByRole("button", { name: /^Эллипс/ }).click();
  await editor.mouse.click(700, 460);
  await expect(canvas(page).locator("ellipse")).toHaveCount(1);
  await saved(editor);
  await page.mouse.move(initial.x + 20, initial.y + 20);
  await page.mouse.down();
  await page.mouse.move(initial.x + 170, initial.y + 100, { steps: 8 });
  await page.mouse.up();
  await expect.poll(async () => (await rectangle.boundingBox())?.x ?? 0).toBeGreaterThan(initial.x + 100);
  await saved(page);
  await page.getByRole("button", { name: /^Отменить/ }).click();
  await expect.poll(async () => Math.round((await rectangle.boundingBox())?.x ?? 0)).toBe(Math.round(initial.x));
  await expect(canvas(page).locator("ellipse")).toHaveCount(1);
  await expect(canvas(editor).locator("ellipse")).toHaveCount(1);
  await saved(page);
  const viewer = await scenario.guest(await invitation(page, "viewer"), "E2E зритель");
  await expect(viewer.getByText("Только просмотр", { exact: true })).toBeVisible();
  await expect(viewer.getByRole("button", { name: /^Прямоугольник/ })).toHaveCount(0);
  await expect(canvas(viewer).locator("ellipse")).toHaveCount(1);
  await page.getByRole("button", { name: "Поделиться", exact: true }).click();
  await page.getByLabel("Отозвать доступ: E2E ученик", { exact: true }).click();
  await expect(editor.getByText(/Доступ к доске прекращён/)).toBeVisible({ timeout: 10_000 });
  await expect(editor.getByRole("button", { name: /^Прямоугольник/ })).toHaveCount(0);
  await page.keyboard.press("Escape");
});

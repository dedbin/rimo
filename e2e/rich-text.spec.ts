import { test, expect } from "./fixtures";
import { canvas, finishText, insertText, invitation, openBoard, saved, texts } from "./board-ui";

test("rich text, math and Markdown survive two editors, local undo and reload", async ({ page, scenario }) => {
  const boardId = await scenario.createBoard("E2E русский текст и формулы");
  await openBoard(page, boardId);
  const peer = await scenario.guest(await invitation(page, "editor"), "E2E текстовый редактор");
  const block = await insertText(page, "Русская математика");
  const editor = page.getByRole("textbox", { name: "Текст на доске", exact: true });
  await editor.press("Control+a");
  await page.getByRole("button", { name: "Жирный", exact: true }).click();
  await expect(texts(peer).locator("strong")).toHaveText("Русская математика");
  await editor.press("Control+End");
  await editor.press("Enter");
  await page.getByRole("button", { name: "Формула в строке", exact: true }).click();
  await page.getByLabel("Исходник формулы LaTeX", { exact: true }).fill("x^2 + y^2 = 1");
  await page.getByRole("button", { name: "Сохранить формулу", exact: true }).click();
  await finishText(page);
  await expect(texts(peer).locator('[data-math-source="x^2 + y^2 = 1"] .katex')).toBeVisible();
  await block.dblclick();
  await page.getByRole("button", { name: "Импорт и экспорт Markdown", exact: true }).click();
  await page.getByLabel("Исходник Markdown", { exact: true }).fill("## Контрольный урок\n\n**Условие** и *решение*.\n\n1. Найти корни\n2. Проверить\n\n$x^2$\n\n$$\n\\frac{1}{2}\n$$\n\nФинал");
  await page.getByRole("button", { name: "Заменить текст", exact: true }).click();
  await finishText(page);
  await expect(texts(peer).locator("h2")).toHaveText("Контрольный урок");
  await expect(texts(peer).locator("ol li")).toHaveCount(2);
  await expect(texts(peer).locator("[data-math-source] .katex")).toHaveCount(2);
  await block.dblclick();
  await page.mouse.move(-10, -10);
  await texts(peer).dblclick();
  const peerEditor = peer.getByRole("textbox", { name: "Текст на доске", exact: true });
  await page.bringToFront();
  await editor.press("Control+End");
  await editor.pressSequentially(" Владелец");
  await expect(peerEditor).toContainText(" Владелец");
  await peer.bringToFront();
  await peerEditor.locator("h2").click({ position: { x: 4, y: 4 } });
  await peerEditor.press("Home");
  await peerEditor.pressSequentially("Ученик ");
  await expect(texts(peer).locator("h2")).toHaveText("Ученик Контрольный урок");
  await expect(editor).toContainText("Ученик ");
  await expect(peerEditor).toContainText(" Владелец");
  await page.bringToFront();
  await editor.press("Control+z");
  await expect(editor).not.toContainText(" Владелец");
  await expect(editor).toContainText("Ученик ");
  await finishText(page);
  await finishText(peer);
  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(canvas(page)).toBeVisible();
  await saved(page);
  await expect(texts(page).locator("h2")).toContainText("Контрольный урок");
  await expect(texts(page)).toContainText("Ученик ");
  await expect(texts(page).locator("[data-math-source] .katex")).toHaveCount(2);
  await expect.poll(() => texts(page).locator("[data-math-source]").evaluateAll((nodes) => nodes.map((node) => node.getAttribute("data-math-source")))).toContain("\\frac{1}{2}");
});

import { readFile } from "node:fs/promises";

import sharp from "sharp";

import { test, expect } from "./fixtures";
import { finishText, images, insertText, openBoard, saved, selectAll, texts, uploadImage } from "./board-ui";

test("named frame PDF preview/download and portable archive restore work through the UI", async ({ page, scenario }, info) => {
  test.setTimeout(120_000);
  const boardId = await scenario.createBoard("E2E PDF и переносимый архив");
  await openBoard(page, boardId);
  await insertText(page, "Контрольный русский урок");
  await page.getByRole("button", { name: "Формула в строке", exact: true }).click();
  await page.getByLabel("Исходник формулы LaTeX", { exact: true }).fill("a^2+b^2=c^2");
  await page.getByRole("button", { name: "Сохранить формулу", exact: true }).click();
  await finishText(page);
  await uploadImage(page, await sharp({ create: { width: 64, height: 32, channels: 4, background: "#7c3aed" } }).png().toBuffer());
  await expect(images(page)).toHaveCount(1);
  await selectAll(page);
  await page.getByRole("button", { name: "PDF", exact: true }).click();
  await page.getByRole("button", { name: "Добавить фрейм по выделению или координатам", exact: true }).click();
  await page.getByLabel("Имя нового фрейма", { exact: true }).fill("E2E урок");
  await page.getByRole("button", { name: "Добавить фрейм", exact: true }).click();
  await page.getByLabel("Экспортировать фрейм E2E урок", { exact: true }).check();
  const prepared = page.waitForResponse((response) => new URL(response.url()).pathname.endsWith("/pdf/preview") && response.request().method() === "POST");
  const previewPage = page.waitForResponse((response) => new URL(response.url()).pathname.includes("/pdf/preview/") && response.request().method() === "GET");
  await page.getByRole("button", { name: "Создать предпросмотр", exact: true }).click();
  const previewResponse = await prepared;
  expect(previewResponse.status()).toBe(201);
  const preview = await previewResponse.json() as { revision: number };
  expect((await previewPage).status()).toBe(200);
  await expect(page.frameLocator('iframe[title="Предпросмотр: E2E урок"]').locator(".rich-text")).toContainText("Контрольный русский урок");
  const acceptance = page.getByLabel("Я проверил масштаб и границы всех страниц", { exact: true });
  if (await acceptance.count()) await acceptance.check();
  const pdfEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Скачать PDF", exact: true }).click();
  const pdf = await pdfEvent;
  expect(pdf.suggestedFilename()).toBe(`rimo-${boardId}-r${preview.revision}.pdf`);
  const pdfPath = info.outputPath("lesson.pdf");
  await pdf.saveAs(pdfPath);
  expect((await readFile(pdfPath)).subarray(0, 5).toString()).toBe("%PDF-");
  await page.keyboard.press("Escape");
  const archiveEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Действия с доской", exact: true }).click();
  await page.getByRole("button", { name: "Архив", exact: true }).click();
  const archive = await archiveEvent;
  const archivePath = info.outputPath("lesson.rimo");
  await archive.saveAs(archivePath);
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Действия с доской", exact: true }).click();
  const imported = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/boards/import" && response.request().method() === "POST");
  await page.getByLabel("Архив Rimo", { exact: true }).setInputFiles(archivePath);
  const importResponse = await imported;
  expect(importResponse.status()).toBe(201);
  await page.waitForURL((url) => /^\/board\/[a-f0-9-]{36}$/.test(url.pathname) && url.pathname !== `/board/${boardId}`);
  const restoredId = new URL(page.url()).pathname.split("/").at(-1)!;
  scenario.createdBoards.add(restoredId);
  expect(restoredId).not.toBe(boardId);
  await saved(page);
  await expect(texts(page)).toContainText("Контрольный русский урок");
  await expect(texts(page).locator('[data-math-source="a^2+b^2=c^2"] .katex')).toBeVisible();
  await expect(images(page)).toHaveCount(1);
  await page.getByRole("button", { name: "PDF", exact: true }).click();
  await page.getByLabel("Фреймы", { exact: true }).check();
  await expect(page.getByLabel("Экспортировать фрейм E2E урок", { exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
});
